import type { EventCategory, EventItem } from './types';

/**
 * 「グルメ」と「エンタメ」の最終判定。収集時のカテゴリを、読み込み時にここで直す。
 *
 * 収集側の判定は「タイトルに食・肉・パンが入る」「ウォーカープラスのグルメ一覧に載っている」
 * だけでグルメにしていたので、ビアガーデン・ホテルのビュッフェ・食虫植物展まで混ざっていた。
 * グルメの絞り込みで見たいのは肉フェスのような**食べ物そのものが主役の催し**なので、
 * 「食べ物の語」と「催しの語」が並んでいるものだけをグルメにする。
 *
 * 読み込み時に直すのは、収集し直さなくても（公開中の暗号化データにも）すぐ効くようにするため。
 */

/** 主役になる食べ物・飲み物。 */
const FOOD_WORD =
  '肉|焼肉|ホルモン|ステーキ|ラーメン|らーめん|拉麺|つけ麺|麺|うどん|そば|蕎麦|餃子|ぎょうざ|ギョーザ|' +
  'カレー|グルメ|フード|食|美食|ビール|ビア|ワイン|日本酒|地酒|酒|ハイボール|ウイスキー|' +
  'スイーツ|パン(?!ダ)|ケーキ|チョコ|プリン|かき氷|クレープ|ドーナツ|和菓子|シェイク|アイス|ジェラート|' +
  '牛(?!久)|豚|鶏|魚|蟹|かに|カニ|伊勢エビ|伊勢えび|しらす|生ハム|おにぎり|やきとり|焼き鳥|' +
  'ラ～メン|ら～めん|バウムクーヘン|レモン|葡萄|ホップ|麦|くいだおれ|美味|うまい|おいしい|んめぇ|旨|' +
  'キッチンカー|YATAI|ヤタイ|EAT|の味|収穫|' +
  'フルーツ|果物|抹茶|新米|味覚|うまいもん|食いしん|まんぷく|大食い|' +
  'コーヒー|珈琲|紅茶|チーズ|からあげ|唐揚げ|から揚げ|焼きそば|やきそば|たこ焼|お好み焼|' +
  'ハンバーガー|バーガー|ピザ|タコス|ケバブ|寿司|すし|鮨|海鮮|牡蠣|かき|カキ|さんま|秋刀魚|' +
  'おでん|鍋|丼|もつ|牛タン|ジビエ|餅|もち|いちご|苺|メロン|ぶどう|梨|りんご|芋|いも|' +
  '屋台|B-?1|Ｂ－?１';

/** 「〇〇フェス」「〇〇祭」などの催しの語。 */
const EVENT_WORD =
  'フェス|フェスタ|フェスティバル|祭|まつり|EXPO|エキスポ|博|グランプリ|サミット|甲子園|選手権|' +
  '大集合|の陣|万博|食べ比べ|食べ歩き|横丁|大会|市場|マーケット';

const FOOD_EVENT = new RegExp(`(${FOOD_WORD})[^\\s　「」『』]{0,8}?(${EVENT_WORD})`);
const FOOD_EVENT_EN =
  /(food|gourmet|beers?|wine|sake|ramen|curry|sweets|coffee|meat|bbq|taco|burger)[\w\s]{0,15}?(fes|fest|festival|expo|carnival)|oktoberfest|オクトーバーフェスト|物産展|物産(まつり|祭)|夜市|KANPAI|乾杯/i;

/** 食べ物が主役でも「催し」ではないもの。飲食店の季節メニューや展示・講座。 */
const NOT_FOOD_EVENT =
  /ビアガーデン|ビヤガーデン|ビアテラス|ビアホール|ビュッフェ|ブッフェ|バイキング|アフタヌーンティー|ティーパーティー|カフェ|ランチ|ディナー|プラン|食べ放題|講座|教室|体験|狩り|つかみ|釣り|展(示|覧)?(?!望)|植物|図鑑|食品サンプル|スタンプラリー|ツアー|クルーズ|列車|フェア|神社|大祭|例祭|奉納|競べ|フリーマーケット|フリマ|ハンドメイド|手作り|セリ市|講演/;

/** 体験型の展示・謎解き・キャラクターもの・舞台など、遊びに行く催し。 */
const ENTERTAINMENT_RE = new RegExp(
  [
    'すぎる|すぎ展|あるある|だらけ|体験型|参加型|没入|イマーシブ|ポップアップ|POP\\s?UP|コラボ',
    '謎解き|脱出|リアル.{0,4}ゲーム|お化け屋敷|ホラー|チームラボ|プロジェクションマッピング|VR|eスポーツ',
    'キャラクター|アニメ|漫画|マンガ|まんが|ゲーム|劇場版|サンリオ|ポケモン|ちいかわ|ジブリ|ディズニー|ピクサー',
    'ドラえもん|アンパンマン|すみっコ|リラックマ|スヌーピー|ミッフィー|ピングー|たべっ子|呪術|鬼滅|ワンピース',
    'ガンダム|ウルトラマン|仮面ライダー|プリキュア|ハリー・?ポッター|ホグワーツ|刃牙|妖怪|コナン',
    'お笑い|漫才|落語|寄席|演劇|舞台|ミュージカル|サーカス|マジック|イリュージョン|ショー(?!ト|ケース)',
    'ばえる|映える|インスタ|超.{1,6}展|ざんねん',
  ].join('|'),
  'i',
);

/** 美術館・博物館の企画展はアートのまま。エンタメの語が入っていても優先する。 */
const SERIOUS_EXHIBITION = /美術|博物館|資料館|郷土|没後|生誕|コレクション|名品|国宝|重要文化財|絵画|版画|彫刻|書道|写真展|工芸|陶芸|日本画|浮世絵|絵本/;

/** 催しではなく学ぶ場、または別のカテゴリがはっきりしているもの。エンタメにしない。 */
const NOT_ENTERTAINMENT = /講座|セミナー|講演|研修|養成|フォーラム|教室|塾|花火|ビアガーデン|アフタヌーンティー|ハイティー|ティーセット/;

/** 祭り・花火・音楽・スポーツはそれ自体がはっきりしているので、エンタメで上書きしない。 */
const KEEP_AS_IS: EventCategory[] = ['music', 'festival', 'sports', 'tech'];

/** 収集時の判定がグルメだったが、ここで外したものの行き先。 */
const FALLBACK_RULES: [RegExp, EventCategory][] = [
  [/祭|花火|山車|神輿|盆踊り|灯籠|イルミネーション/, 'festival'],
  [/ライブ|音楽|コンサート|ジャズ|DJ/, 'music'],
  [/マルシェ|市$|朝市|フリーマーケット|物産|フェア|蚤の市/, 'market'],
  [/展|美術|アート|ミュージアム/, 'art'],
];

/*
 * 「ウォーカープラスのグルメ一覧に載っている＋祭・フェス」も試したが、
 * あの一覧には町の秋祭りや花火大会も載っていて大量に混ざった。
 * 取りこぼしは FOOD_WORD に語を足して拾う（例: 房総 生シェイク祭り → シェイク）。
 */
export function isFoodEvent(title: string): boolean {
  if (NOT_FOOD_EVENT.test(title)) return false;
  return FOOD_EVENT.test(title) || FOOD_EVENT_EN.test(title);
}

export function isEntertainment(title: string): boolean {
  return (
    ENTERTAINMENT_RE.test(title) && !SERIOUS_EXHIBITION.test(title) && !NOT_ENTERTAINMENT.test(title)
  );
}

export function classify(ev: EventItem): EventCategory {
  // 判定はタイトルだけで行う。説明文には「グルメも楽しめる」のような添え物の話が多く、
  // それで拾うとまた「少しでも食に関係あるもの」が混ざる
  const title = ev.title;

  if (isFoodEvent(title)) return 'food';
  if (KEEP_AS_IS.includes(ev.category)) return ev.category;
  if (isEntertainment(title)) return 'entertainment';
  if (ev.category !== 'food') return ev.category;

  for (const [re, cat] of FALLBACK_RULES) {
    if (re.test(title)) return cat;
  }
  return 'other';
}

/** 読み込んだ全イベントのカテゴリをその場で直す。 */
export function reclassify(events: EventItem[]): void {
  for (const ev of events) ev.category = classify(ev);
}
