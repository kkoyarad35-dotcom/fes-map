/** 美術館・博物館の企画展はアートのまま。エンタメの語が入っていても優先する。 */
const SERIOUS_EXHIBITION = /美術|資料館|郷土|没後|生誕|コレクション|名品|国宝|重要文化財|絵画|版画|彫刻|書道|写真展|工芸|陶芸|日本画|浮世絵|絵本|歴史|考古|古文書|刀剣|日本刀|仏像/;

/** 催しではなく学ぶ場、または別のカテゴリがはっきりしているもの。エンタメにしない。 */
